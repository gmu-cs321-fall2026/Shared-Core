-- 007_create_applications.sql
-- Applications submitted by users for jobs.
-- Job records are owned by another subsystem; job_id is kept as an identifier here
-- until that subsystem's database contract is available for a cross-subsystem FK.

CREATE TYPE application_status AS ENUM (
    'submitted',
    'under_review',
    'rejected',
    'accepted',
    'withdrawn'
);

CREATE TABLE applications (
    application_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id         INT NOT NULL,
    user_id        UUID NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    status         application_status NOT NULL DEFAULT 'submitted',
    resume_url     TEXT,
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    submitted_at   TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT applications_one_per_user_job UNIQUE (user_id, job_id)
);

CREATE INDEX applications_job_id_idx ON applications (job_id);
CREATE INDEX applications_status_idx ON applications (status);
CREATE INDEX applications_user_submitted_idx ON applications (user_id, submitted_at DESC);

CREATE FUNCTION set_applications_updated_at() RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER applications_updated_at
    BEFORE UPDATE ON applications
    FOR EACH ROW EXECUTE FUNCTION set_applications_updated_at();
